def parse():
    tasks = []
    for raw in TABLE.strip().splitlines():
        raw = raw.strip()
        if not raw:
            continue
        parts = raw.split("|")
        tid, batch, group, scope, kind, title, desc, accept = parts[:8]
        files = parts[8].split(";") if len(parts) > 8 and parts[8].strip() else []
        low = tid.lower()
        if not files and kind == "ui":
            files = [
                f"java/feature/{low}/{tid}Activity.kt",
                f"java/feature/{low}/{tid}Module.kt",
                f"java/feature/{low}/{tid}Engine.kt",
                f"res/layout/activity_{low}.xml",
                f"res/values/strings_{low}.xml",
            ]
        tasks.append({
            "id": tid,
            "batch": int(batch),
            "group": group,
            "scope": scope,
            "kind": kind,
            "title": title,
            "summary": desc,
            "acceptance": [a for a in accept.split(";") if a.strip()],
            "touch_files": files,
        })
    return tasks

def main():
    tasks = parse()
    ids = [t["id"] for t in tasks]
    assert len(tasks) == 100, f"任务数 {len(tasks)}"
    assert len(set(ids)) == 100, "id 重复"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"tasks": tasks}, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"写入 {OUT} 共 {len(tasks)} 项")
    from collections import Counter
    print("批次分布:", dict(sorted(Counter(t["batch"] for t in tasks).items())))

if __name__ == "__main__":
    main()
